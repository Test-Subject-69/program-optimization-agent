const monthIndexByLabel = {
  Jan: 1,
  Feb: 2,
  Mar: 3,
  Apr: 4,
  May: 5,
  Jun: 6,
  Jul: 7,
  Aug: 8,
  Sep: 9,
  Oct: 10,
  Nov: 11,
  Dec: 12
};

function isoDateForMonth(monthIndex) {
  return `2026-${String(monthIndex).padStart(2, "0")}-28T12:00:00.000Z`;
}

function scaledMetric(value, factor, fallback = 0) {
  const numeric = Number(value);
  if (!Number.isFinite(numeric)) return fallback;
  return Math.max(fallback, Math.round(numeric * factor));
}

export const sampleKpiSnapshots = samplePrograms.flatMap((program) =>
  (program.monthlyTrend ?? []).map((entry, index, trend) => {
    const monthIndex = monthIndexByLabel[entry.month] ?? index + 1;
    const progressFactor = (index + 1) / Math.max(trend.length, 1);
    return {
      id: `${program.id}-snapshot-${String(monthIndex).padStart(2, "0")}`,
      programId: program.id,
      periodLabel: `2026-${String(monthIndex).padStart(2, "0")}`,
      recordedAt: isoDateForMonth(monthIndex),
      householdsServed: entry.served,
      householdsTarget: entry.target,
      staffingCapacityPct: Math.max(45, Math.round((program.metrics.staffingCapacityPct ?? 0) - (trend.length - index - 1))),
      backlogCount: scaledMetric(program.metrics.backlogCount, 0.45 + progressFactor * 0.55),
      complianceScore: Math.min(100, Math.max(70, Math.round((program.metrics.complianceScore ?? 0) - (trend.length - index - 1) * 0.5))),
      dataFreshnessHours: Math.max(4, Math.round((program.metrics.dataFreshnessHours ?? 0) * (1 - progressFactor * 0.15)))
    };
  })
);

